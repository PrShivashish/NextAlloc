-- V7: Operational offer lifecycle and seat management
CREATE TABLE IF NOT EXISTS offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    candidate_id BIGINT NOT NULL,
    opportunity_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OFFERED',
    offered_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMP WITH TIME ZONE,
    joined_at TIMESTAMP WITH TIME ZONE,
    decline_reason VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_offer_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles(id) ON DELETE CASCADE,
    CONSTRAINT fk_offer_opportunity FOREIGN KEY (opportunity_id) REFERENCES opportunities(id) ON DELETE CASCADE,
    CONSTRAINT uq_offer_run_candidate UNIQUE (run_id, candidate_id)
);

CREATE INDEX IF NOT EXISTS idx_offer_candidate_status ON offers(candidate_id, status);
CREATE INDEX IF NOT EXISTS idx_offer_opp_status ON offers(opportunity_id, status);
CREATE INDEX IF NOT EXISTS idx_offer_run ON offers(run_id);

