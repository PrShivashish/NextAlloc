-- V1__baseline_schema.sql
-- NextAlloc baseline schema representing the pre-Phase-4A original application tables.
-- Idempotent, compliant with H2 and standard SQL dialects.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(190) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(120) NOT NULL,
    role VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS candidate_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(30),
    dob DATE,
    qualification VARCHAR(30),
    candidate_status VARCHAR(20),
    state VARCHAR(60),
    district VARCHAR(60),
    location_type VARCHAR(20),
    bio VARCHAR(600),
    experience_years DOUBLE PRECISION NOT NULL,
    candidate_state VARCHAR(20) NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_candidate_user UNIQUE (user_id)
);
CREATE INDEX IF NOT EXISTS idx_candidate_state ON candidate_profiles(state);
CREATE INDEX IF NOT EXISTS idx_candidate_cstate ON candidate_profiles(candidate_state);

CREATE TABLE IF NOT EXISTS candidate_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    raw_label VARCHAR(80) NOT NULL,
    canonical VARCHAR(80) NOT NULL,
    source VARCHAR(20) NOT NULL,
    validated BOOLEAN NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_skill_candidate ON candidate_skills(candidate_id);

CREATE TABLE IF NOT EXISTS candidate_interests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    sector VARCHAR(40) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_interest_candidate ON candidate_interests(candidate_id);

CREATE TABLE IF NOT EXISTS candidate_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    opportunity_id BIGINT NOT NULL,
    rank INT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_pref_cand_opp UNIQUE (candidate_id, opportunity_id)
);
CREATE INDEX IF NOT EXISTS idx_pref_candidate ON candidate_preferences(candidate_id);
CREATE INDEX IF NOT EXISTS idx_pref_opportunity ON candidate_preferences(opportunity_id);

CREATE TABLE IF NOT EXISTS opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL,
    title VARCHAR(160) NOT NULL,
    sector VARCHAR(40) NOT NULL,
    state VARCHAR(60) NOT NULL,
    city VARCHAR(80),
    capacity INT NOT NULL,
    duration_months INT NOT NULL,
    min_qualification VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    description VARCHAR(800),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_opp_provider ON opportunities(provider_id);
CREATE INDEX IF NOT EXISTS idx_opp_sector ON opportunities(sector);
CREATE INDEX IF NOT EXISTS idx_opp_state ON opportunities(state);

CREATE TABLE IF NOT EXISTS opportunity_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id BIGINT NOT NULL,
    skill VARCHAR(80) NOT NULL,
    mandatory BOOLEAN NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_oskill_opp ON opportunity_skills(opportunity_id);

CREATE TABLE IF NOT EXISTS providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    org_name VARCHAR(160) NOT NULL,
    org_type VARCHAR(80),
    state VARCHAR(60),
    about VARCHAR(600),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_provider_user UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS resume_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    stored_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(120),
    size_bytes BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    skills_json VARCHAR(2000),
    suggestions_json VARCHAR(8000),
    status_message VARCHAR(500),
    text_length INT NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_resume_user ON resume_files(user_id);

CREATE TABLE IF NOT EXISTS dataset_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario VARCHAR(40) NOT NULL,
    version INT NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    seed BIGINT NOT NULL,
    candidate_count INT NOT NULL,
    opportunity_count INT NOT NULL,
    seat_count INT NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_snapshot_scenario ON dataset_snapshots(scenario);

CREATE TABLE IF NOT EXISTS allocation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL,
    number INT NOT NULL,
    run_code VARCHAR(40) NOT NULL,
    scenario VARCHAR(40) NOT NULL,
    policy_key VARCHAR(40) NOT NULL,
    policy_name VARCHAR(120) NOT NULL,
    policy_version VARCHAR(20) NOT NULL,
    weights_json VARCHAR(500) NOT NULL,
    full_coverage BOOLEAN NOT NULL,
    fairness_floor_pct INT,
    fairness_groups_json VARCHAR(1000),
    overrides_json VARCHAR(2000),
    changes_json VARCHAR(1000),
    parent_run_id BIGINT,
    status VARCHAR(20) NOT NULL,
    solver_status VARCHAR(20),
    objective BIGINT,
    eligible_pairs INT NOT NULL DEFAULT 0,
    variables INT NOT NULL DEFAULT 0,
    constraints INT NOT NULL DEFAULT 0,
    solver_runtime_ms BIGINT NOT NULL DEFAULT 0,
    total_runtime_ms BIGINT NOT NULL DEFAULT 0,
    stage_timings_json VARCHAR(2000),
    error_message VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT uq_run_code UNIQUE (run_code)
);
CREATE INDEX IF NOT EXISTS idx_run_status ON allocation_runs(status);
CREATE INDEX IF NOT EXISTS idx_run_parent ON allocation_runs(parent_run_id);

CREATE TABLE IF NOT EXISTS assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    candidate_id BIGINT NOT NULL,
    opportunity_id BIGINT NOT NULL,
    source VARCHAR(20) NOT NULL,
    suitability DOUBLE PRECISION NOT NULL,
    skills_fit DOUBLE PRECISION NOT NULL,
    qualification_fit DOUBLE PRECISION NOT NULL,
    interest_fit DOUBLE PRECISION NOT NULL,
    location_fit DOUBLE PRECISION NOT NULL,
    preference_fit DOUBLE PRECISION NOT NULL,
    learning_fit DOUBLE PRECISION NOT NULL,
    experience_fit DOUBLE PRECISION NOT NULL,
    breakdown_json VARCHAR(800),
    reason VARCHAR(600),
    CONSTRAINT uq_assign_run_cand_src UNIQUE (run_id, candidate_id, source)
);
CREATE INDEX IF NOT EXISTS idx_assign_run ON assignments(run_id);
CREATE INDEX IF NOT EXISTS idx_assign_candidate ON assignments(candidate_id);
CREATE INDEX IF NOT EXISTS idx_assign_opp ON assignments(opportunity_id);

CREATE TABLE IF NOT EXISTS simulation_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_run_id BIGINT NOT NULL,
    policy_name VARCHAR(120) NOT NULL,
    weights_json VARCHAR(500) NOT NULL,
    full_coverage BOOLEAN NOT NULL,
    fairness_floor_pct INT,
    status VARCHAR(20) NOT NULL,
    solver_status VARCHAR(20),
    metrics_json VARCHAR(4000),
    affected_count INT NOT NULL,
    stability DOUBLE PRECISION NOT NULL,
    runtime_ms BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sim_base ON simulation_runs(base_run_id);

CREATE TABLE IF NOT EXISTS policy_presets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    preset_key VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(400),
    weights_json VARCHAR(500) NOT NULL,
    full_coverage BOOLEAN NOT NULL,
    fairness_floor_pct INT,
    is_default BOOLEAN NOT NULL,
    version VARCHAR(20) NOT NULL,
    CONSTRAINT uq_policy_key UNIQUE (preset_key)
);

CREATE TABLE IF NOT EXISTS conflict_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    opportunity_id BIGINT NOT NULL,
    eligible_count INT NOT NULL,
    seat_count INT NOT NULL,
    unmet_demand INT NOT NULL,
    pressure DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_conflict_run ON conflict_metrics(run_id);

CREATE TABLE IF NOT EXISTS geo_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    state VARCHAR(60) NOT NULL,
    demand INT NOT NULL,
    capacity INT NOT NULL,
    allocated INT NOT NULL,
    unmet_demand INT NOT NULL,
    pressure DOUBLE PRECISION NOT NULL,
    allocation_rate DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_geo_run ON geo_metrics(run_id);

CREATE TABLE IF NOT EXISTS group_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    group_type VARCHAR(40) NOT NULL,
    group_value VARCHAR(80) NOT NULL,
    population INT NOT NULL,
    allocated INT NOT NULL,
    avg_suitability DOUBLE PRECISION NOT NULL,
    preference_satisfaction DOUBLE PRECISION NOT NULL,
    allocation_rate DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_group_run ON group_metrics(run_id);

CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    actor_name VARCHAR(120),
    action VARCHAR(40) NOT NULL,
    target_type VARCHAR(40),
    target_id VARCHAR(60),
    summary VARCHAR(300) NOT NULL,
    details_json VARCHAR(1500),
    at TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_at ON audit_events(at);

CREATE TABLE IF NOT EXISTS embedding_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_key VARCHAR(120) NOT NULL,
    model_version VARCHAR(40) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    vector_json VARCHAR(4000) NOT NULL,
    dims INT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_embed_key UNIQUE (entity_key, model_version, fingerprint)
);
CREATE INDEX IF NOT EXISTS idx_embed_key ON embedding_cache(entity_key);
