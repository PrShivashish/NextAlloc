-- V6: Additive candidate related skills table for soft suitability evaluation
CREATE TABLE IF NOT EXISTS candidate_related_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    raw_label VARCHAR(80) NOT NULL,
    concept_id VARCHAR(64) NOT NULL,
    related_canonical VARCHAR(80) NOT NULL,
    relationship_type VARCHAR(32) NOT NULL,
    taxonomy_version VARCHAR(32) NOT NULL,
    claim_source VARCHAR(32) NOT NULL DEFAULT 'SELF_DECLARED',
    evidence_status VARCHAR(32) NOT NULL DEFAULT 'UNVERIFIED',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_cand_related_skill_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles(id) ON DELETE CASCADE,
    CONSTRAINT uq_cand_related_skill UNIQUE (candidate_id, concept_id)
);

CREATE INDEX IF NOT EXISTS idx_cand_related_skill_cand ON candidate_related_skills(candidate_id);
CREATE INDEX IF NOT EXISTS idx_cand_related_skill_concept ON candidate_related_skills(concept_id);
CREATE INDEX IF NOT EXISTS idx_cand_related_skill_canonical ON candidate_related_skills(related_canonical);
