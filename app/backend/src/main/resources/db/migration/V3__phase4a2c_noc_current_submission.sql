-- Additive, non-destructive migration for NextAlloc Phase 4A-2C
-- Establishes single authoritative active evidence pointer table with composite ownership enforcement.

-- 1. Add composite unique constraint on candidate_evidences so current pointer can enforce candidate & type ownership
ALTER TABLE candidate_evidences
ADD CONSTRAINT uq_cand_evid_composite UNIQUE (id, candidate_id, evidence_type);

-- 2. Create candidate_evidence_current with composite foreign key to guarantee ownership integrity
CREATE TABLE IF NOT EXISTS candidate_evidence_current (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    evidence_type VARCHAR(40) NOT NULL,
    evidence_id BIGINT NOT NULL,
    version INT DEFAULT 0 NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cand_evid_current UNIQUE (candidate_id, evidence_type),
    CONSTRAINT fk_evid_cur_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles(id) ON DELETE CASCADE,
    CONSTRAINT fk_evid_cur_evidence_ownership FOREIGN KEY (evidence_id, candidate_id, evidence_type)
        REFERENCES candidate_evidences(id, candidate_id, evidence_type) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_evid_cur_lookup ON candidate_evidence_current(candidate_id, evidence_type);

-- 3. Strict, unambiguous backfill:
-- Only backfill candidates with EXACTLY ONE legacy evidence record for that type.
-- Ambiguous cases (multiple legacy records without explicit pointer) are NOT silently resolved.
INSERT INTO candidate_evidence_current (candidate_id, evidence_type, evidence_id, version, updated_at)
SELECT ce.candidate_id, ce.evidence_type, ce.id, 0, CURRENT_TIMESTAMP
FROM candidate_evidences ce
WHERE (ce.candidate_id, ce.evidence_type) IN (
    SELECT sub.candidate_id, sub.evidence_type
    FROM candidate_evidences sub
    GROUP BY sub.candidate_id, sub.evidence_type
    HAVING COUNT(sub.id) = 1
);
