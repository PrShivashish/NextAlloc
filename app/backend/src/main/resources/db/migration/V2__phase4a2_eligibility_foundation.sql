-- V2__phase4a2_eligibility_foundation.sql
-- Additive, non-destructive migration for NextAlloc Phase 4A-2A
-- Introduces versioned eligibility metadata, academic enrollment status, institutional NOC evidence, and snapshot ledger scaffold.

-- 1. Extend allocation_runs with rule-set identifiers
ALTER TABLE allocation_runs 
ADD COLUMN IF NOT EXISTS eligibility_ruleset_id VARCHAR(50) DEFAULT 'prototype-legacy-v1' NOT NULL;

ALTER TABLE allocation_runs 
ADD COLUMN IF NOT EXISTS eligibility_ruleset_version VARCHAR(30) DEFAULT '1.0.0' NOT NULL;

-- 2. Extend candidate_profiles with employment classification
ALTER TABLE candidate_profiles 
ADD COLUMN IF NOT EXISTS employment_type VARCHAR(30) DEFAULT 'UNKNOWN';

-- 3. Create candidate_academic_records
CREATE TABLE IF NOT EXISTS candidate_academic_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    enrollment_status VARCHAR(30) DEFAULT 'UNKNOWN' NOT NULL,
    degree_program VARCHAR(120),
    institution_name VARCHAR(200),
    institution_aishe_code VARCHAR(30),
    current_academic_year INT,
    program_duration_years INT,
    final_year_status VARCHAR(30) DEFAULT 'UNKNOWN' NOT NULL,
    expected_completion_date DATE,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_acad_candidate UNIQUE (candidate_id),
    CONSTRAINT fk_acad_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_acad_candidate ON candidate_academic_records(candidate_id);

-- 4. Create candidate_evidences
CREATE TABLE IF NOT EXISTS candidate_evidences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id BIGINT NOT NULL,
    evidence_type VARCHAR(40) NOT NULL,
    document_reference VARCHAR(300) NOT NULL,
    document_sha256 VARCHAR(64),
    issuing_institution VARCHAR(200),
    signatory_role VARCHAR(40),
    signatory_name VARCHAR(120),
    signatory_email VARCHAR(120),
    declares_no_academic_conflict BOOLEAN DEFAULT FALSE NOT NULL,
    valid_from DATE,
    valid_until DATE,
    verification_status VARCHAR(30) DEFAULT 'NOT_SUBMITTED' NOT NULL,
    verified_at TIMESTAMP,
    verified_by_user_id BIGINT,
    rejection_reason_code VARCHAR(50),
    rejection_notes VARCHAR(500),
    version INT DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_evid_candidate FOREIGN KEY (candidate_id) REFERENCES candidate_profiles(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_evid_candidate_type ON candidate_evidences(candidate_id, evidence_type);
CREATE INDEX IF NOT EXISTS idx_evid_status ON candidate_evidences(verification_status);

-- 5. Create allocation_eligibility_snapshots
CREATE TABLE IF NOT EXISTS allocation_eligibility_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL,
    candidate_id BIGINT NOT NULL,
    decision VARCHAR(30) NOT NULL,
    reason_codes_json TEXT,
    evidence_status_snapshot VARCHAR(40),
    evidence_id_ref BIGINT,
    evaluated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_run_candidate_elig UNIQUE (run_id, candidate_id),
    CONSTRAINT fk_eligsanp_run FOREIGN KEY (run_id) REFERENCES allocation_runs(id) ON DELETE RESTRICT,
    CONSTRAINT fk_eligsanp_cand FOREIGN KEY (candidate_id) REFERENCES candidate_profiles(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_eligsanp_run_cand ON allocation_eligibility_snapshots(run_id, candidate_id);

